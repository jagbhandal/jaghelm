#!/usr/bin/env node
// Builds server/themeBases.js (#331) from src/ui/tokens.css: the colour roles
// each built-in theme paints, which a custom theme overrides, so the theme
// validator (server/themes.js) can run the contrast rules on the whole result
// in the browser and in the server, which hold no CSS.
//
//   node scripts/theme-bases.mjs          rewrite server/themeBases.js
//   node scripts/theme-bases.mjs --check  exit 1 if it is out of date
//
// scripts/theme-bases.test.mjs fails when the committed file differs from
// what tokens.css gives, so a token change cannot leave the validator behind.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ACCENTS, THEMES, TOKENS_FILE, readTokens, resolveContext } from './ui-contrast.mjs';
import { DEFAULT_ACCENT } from '../src/ui/accents.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT_FILE = path.join(ROOT, 'server/themeBases.js');

// Palette steps (graphite-198, violet-541...): roles read them, a theme never does.
const PALETTE = /^(?:graphite|violet|green|amber|red|steel|blue)-\d+$|^white$/;
// The sequential ramp keeps the built-in's values: its shape is a chart gate, not a pairing.
const NOT_OVERRIDABLE = /^seq-\d+$/;

/** `value` with each var() of a palette step replaced by the step's colour. */
function resolvePalette(props, value) {
  const ref = value.trim().match(/^var\(\s*--jh-([\w-]+)\s*\)$/);
  if (!ref || !PALETTE.test(ref[1])) return value.trim();
  return resolvePalette(props, props[`--jh-${ref[1]}`]);
}

/** Every colour role in effect in `props`: name (no --jh-) to colour, or var() of another role. */
function colourRoles(props) {
  const roles = {};
  for (const [prop, raw] of Object.entries(props)) {
    const name = prop.slice('--jh-'.length);
    if (PALETTE.test(name) || NOT_OVERRIDABLE.test(name)) continue;
    const value = resolvePalette(props, raw);
    if (/^oklch\(/.test(value) || /^var\(--jh-[\w-]+\)$/.test(value)) roles[name] = value;
  }
  return roles;
}

/** { bases, accents } from tokens.css: each theme's roles, and each other accent's difference from the default one. */
export function buildThemeBases(css) {
  const { rules } = readTokens(css);
  const bases = {};
  const accents = {};
  for (const theme of THEMES) {
    bases[theme] = colourRoles(resolveContext(rules, { theme, accent: DEFAULT_ACCENT }));
    accents[theme] = {};
    for (const accent of ACCENTS.filter((a) => a !== DEFAULT_ACCENT)) {
      const roles = colourRoles(resolveContext(rules, { theme, accent }));
      accents[theme][accent] = Object.fromEntries(
        Object.entries(roles).filter(([name, value]) => bases[theme][name] !== value)
      );
    }
  }
  return { bases, accents };
}

/** The text of server/themeBases.js for `css`. */
export function themeBasesSource(css) {
  const { bases, accents } = buildThemeBases(css);
  return `// GENERATED by scripts/theme-bases.mjs from src/ui/tokens.css (#331): do not edit.
// \`npm run theme-bases\` rewrites it; scripts/theme-bases.test.mjs fails when it is stale.
//
// What a custom theme (server/themes.js) overrides: each built-in theme's colour
// roles with the default accent, and for each other accent the roles it changes.

/** Theme to role (no --jh- prefix) to colour, or var() of another role. */
export const THEME_BASES = ${JSON.stringify(bases, null, 2)};

/** Theme to accent to the roles that accent sets differently from the default's. */
export const ACCENT_ROLES = ${JSON.stringify(accents, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = themeBasesSource(readFileSync(TOKENS_FILE, 'utf8'));
  if (process.argv.includes('--check')) {
    const stale = readFileSync(OUT_FILE, 'utf8') !== source;
    if (stale) console.error('server/themeBases.js is out of date: run npm run theme-bases');
    process.exitCode = stale ? 1 : 0;
  } else {
    writeFileSync(OUT_FILE, source);
  }
}
