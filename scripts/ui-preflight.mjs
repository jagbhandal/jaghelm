#!/usr/bin/env node
/**
 * Writes src/ui/preflight.css: Tailwind's preflight (its base reset) wrapped in
 * `@scope (.jh-ui)`, so it resets the new component library (src/ui/) and never
 * today's screens. Global preflight would zero their margins, unstyle their
 * lists and headings and make every <svg> a block. See docs/ARCHITECTURE.md,
 * "UI stack".
 *
 *   node scripts/ui-preflight.mjs           write src/ui/preflight.css
 *   node scripts/ui-preflight.mjs --check   exit 1 when the file is out of date
 *
 * scripts/ui-preflight.test.mjs runs the check under `npm test`, so a Tailwind
 * upgrade that changes preflight fails CI until this script is run again.
 *
 * Two edits besides the wrapper: preflight's `html, :host` rule becomes
 * `:scope` (the scope root takes the root font and line height), and the
 * universal box-model reset also names `:scope`, so the root itself is reset
 * like its descendants.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

export const SCOPE = '.jh-ui';
export const OUT = fileURLToPath(new URL('../src/ui/preflight.css', import.meta.url));

const require = createRequire(import.meta.url);

/** Tailwind's preflight.css and version, as installed. */
export function readTailwindPreflight() {
  const pkg = require('tailwindcss/package.json');
  const css = readFileSync(require.resolve('tailwindcss/preflight.css'), 'utf8');
  return { css, version: pkg.version };
}

function replaceOnce(src, pattern, replacement, what) {
  const hits = src.match(new RegExp(pattern.source, pattern.flags + 'g')) ?? [];
  if (hits.length !== 1) {
    throw new Error(
      `ui-preflight: expected exactly one ${what} in Tailwind's preflight.css, found ${hits.length}. ` +
        'Tailwind changed its preflight: update scripts/ui-preflight.mjs.'
    );
  }
  return src.replace(pattern, replacement);
}

/** Pure transform: Tailwind preflight source -> the scoped file's contents. */
export function scopePreflight(css, version) {
  let body = replaceOnce(css, /^html,\n:host \{/m, ':scope {', '`html, :host` rule');
  body = replaceOnce(body, /^\*,\n::after,/m, ':scope,\n*,\n::after,', 'universal reset rule');
  return [
    '/*',
    ` * GENERATED by scripts/ui-preflight.mjs from tailwindcss@${version} preflight.css`,
    ' * (MIT, Copyright (c) Tailwind Labs, Inc.). Do not edit: run the script.',
    ' *',
    ` * Tailwind's base reset, scoped to ${SCOPE} so it applies to the new UI only`,
    ' * and leaves the screens styled by the legacy CSS alone. src/ui/tailwind.css',
    ' * imports it into the `base` cascade layer.',
    ' */',
    `@scope (${SCOPE}) {`,
    body.trimEnd(),
    '}',
    '',
  ].join('\n');
}

function main() {
  const { css, version } = readTailwindPreflight();
  const want = scopePreflight(css, version);
  if (process.argv.includes('--check')) {
    let have = '';
    try {
      have = readFileSync(OUT, 'utf8');
    } catch {
      // missing file: reported below as out of date
    }
    if (have !== want) {
      console.error('src/ui/preflight.css is out of date: run node scripts/ui-preflight.mjs');
      process.exit(1);
    }
    console.log('src/ui/preflight.css is up to date');
    return;
  }
  writeFileSync(OUT, want);
  console.log(`wrote src/ui/preflight.css from tailwindcss@${version}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
